def build_dataframe() -> pd.DataFrame:
    rows = []
    for i, job in enumerate(JOBS):
        rows.append({
            "岗位名称": job["岗位名称"],
            "地址": job["地址"],
            "薪资范围": job["薪资范围"],
            "公司名称": job["公司名称"],
            "所属行业": job["所属行业"],
            "公司规模": "",
            "公司类型": "",
            "岗位编码": f"MULTI-{i+1:04d}",
            "岗位详情": job["岗位详情"],
            "更新日期": datetime.now().strftime("%Y-%m-%d"),
            "公司详情": "",
            "岗位来源地址": "",
        })
    return pd.DataFrame(rows)


def merge_into_main(new_df: pd.DataFrame) -> None:
    out_path = ROOT / "A13数据_扩展.xlsx"
    if out_path.exists():
        existing = pd.read_excel(out_path)
        merged = pd.concat([existing, new_df], ignore_index=True)
        merged.drop_duplicates(subset=["岗位编码"], keep="last", inplace=True)
    else:
        merged = new_df
    merged.to_excel(out_path, index=False)
    print(f"[merge] wrote {len(merged)} rows -> {out_path}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--merge", action="store_true")
    args = ap.parse_args()

    df = build_dataframe()
    out_xlsx = OUT_DIR / "multi_industry_jobs.xlsx"
    df.to_excel(out_xlsx, index=False)
    print(f"[done] wrote {len(df)} rows -> {out_xlsx}")

    if args.merge:
        merge_into_main(df)


if __name__ == "__main__":
    main()
